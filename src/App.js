const DEFAULT_ENTITY_RATIOS = { OT: 0.03, CPMO: 0.14, PMO: 0.12, EPCM: 0.71 };

function buildProjectArrays(startIdx, endIdx, peakFte, monthlyCost) {
  const fte  = Array(90).fill(0);
  const cost = Array(90).fill(0);
  const ents = { OT: Array(90).fill(0), CPMO: Array(90).fill(0), PMO: Array(90).fill(0), EPCM: Array(90).fill(0) };
  for (let i = startIdx; i <= Math.min(endIdx, 89); i++) {
    fte[i]  = peakFte;
    cost[i] = monthlyCost;
    Object.keys(ents).forEach(e => { ents[e][i] = +(peakFte * DEFAULT_ENTITY_RATIOS[e]).toFixed(2); });
  }
  return { fte, cost, entities: ents };
}

